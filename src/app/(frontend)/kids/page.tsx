import { ThemeLanding } from '../_wake/themeLanding'
import { getParks } from '../_wake/queries'

export const metadata = {
  title: 'Детский вейкборд — парки с детской школой в России',
  description: 'Вейк-парки России с детской школой, обучением, арендой экипировки и инфраструктурой для семейного отдыха.',
}

export default async function KidsPage() {
  const parks = (await getParks(1000)).filter((park) => park.features?.kidsSchool)

  return (
    <ThemeLanding
      config={{
        title: 'Детский вейкборд и семейные парки',
        eyebrow: 'Детская школа',
        description:
          'Подборка площадок, где отмечена детская школа или формат занятий для детей. Подходит для родителей, которые ищут безопасную первую тренировку и понятную инфраструктуру.',
        emptyTitle: 'Пока нет парков с детской школой',
        emptyDescription: 'Отметь услугу «Детская школа» у нужных парков в админке, и они появятся здесь.',
        chips: ['Детская школа', 'Инструктор', 'Безопасность', 'Семейный отдых', 'Экипировка'],
        checklist: [
          'Уточни минимальный возраст и требования к ребёнку.',
          'Проверь наличие детских жилетов, шлемов и подходящих досок.',
          'Спроси, можно ли родителям находиться рядом с зоной старта.',
          'Проверь кафе, раздевалку, душ и парковку, если планируешь провести в парке несколько часов.',
        ],
      }}
      parks={parks}
    />
  )
}
